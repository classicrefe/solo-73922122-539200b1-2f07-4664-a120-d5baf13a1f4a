"""Render the generated sample into a loadable SQL package.

Design rules:

* constraints are never disabled, and NOT DEFERRABLE constraints are never
  rewritten as deferrable;
* circular foreign keys are handled structurally: tables are created without
  their FKs, all data is inserted, then ``ALTER TABLE ... ADD CONSTRAINT``
  installs the exact original constraint definitions;
* every identifier is quoted; NULL is emitted explicitly so NULL semantics
  survive the round trip.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone

from .models import TableSchema
from .solver import Row

HEADER = """-- ============================================================
-- Synthetic referential sample — no real patient values
-- Generated by the data-warehouse sample service
-- All values are solver-produced integers within requested intervals.
-- Load order: 01_schema.sql then 02_data.sql then 03_constraints.sql
-- Every constraint is reproduced exactly as in the source catalog:
-- NOT DEFERRABLE constraints stay immediate (never rewritten as deferred);
-- DEFERRABLE constraints keep their original deferrability clause.
-- ============================================================
"""


def q(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def render_schema(tables: dict[str, TableSchema], selected: list[str]) -> str:
    lines = [HEADER, "BEGIN;\n"]
    for tname in selected:
        ts = tables[tname]
        lines.append(f"CREATE TABLE {q(ts.schema_name)}.{q(ts.name)} (")
        col_defs = []
        for col in ts.columns:
            null_sql = " NOT NULL" if not col.nullable else ""
            col_defs.append(f"    {q(col.name)} {col.pg_type}{null_sql}")
        # PK / UNIQUE constraints that are not foreign keys can live inline;
        # all FKs are deferred to 03_constraints.sql to support cycles.
        for uc in ts.unique_constraints:
            cols = ", ".join(q(c) for c in uc.columns)
            if uc.is_primary:
                col_defs.append(f"    CONSTRAINT {q(uc.name)} PRIMARY KEY ({cols})")
            else:
                col_defs.append(f"    CONSTRAINT {q(uc.name)} UNIQUE ({cols})")
        lines.append(",\n".join(col_defs))
        lines.append(");\n")
    lines.append("COMMIT;\n")
    return "\n".join(lines)


def render_data(
    tables: dict[str, TableSchema], selected: list[str], data: dict[str, list[Row]]
) -> str:
    lines = [HEADER, "BEGIN;\n"]
    for tname in selected:
        ts = tables[tname]
        rows = data[tname]
        if not rows:
            lines.append(f"-- table {q(ts.name)} requested with 0 rows: no INSERTs\n")
            continue
        col_list = ", ".join(q(c.name) for c in ts.columns)
        lines.append(f"INSERT INTO {q(ts.schema_name)}.{q(ts.name)} ({col_list}) VALUES")
        values = []
        for row in rows:
            vals = []
            for col in ts.columns:
                v = row[col.name]
                vals.append("NULL" if v is None else str(v))
            values.append("    (" + ", ".join(vals) + ")")
        lines.append(",\n".join(values) + ";")
        lines.append("")
    lines.append("COMMIT;\n")
    return "\n".join(lines)


def _fk_sql(ts: TableSchema, fk) -> str:
    cols = ", ".join(q(c) for c in fk.columns)
    refs = ", ".join(q(c) for c in fk.ref_columns)
    defer = " DEFERRABLE INITIALLY DEFERRED" if fk.initially_deferred else (
        " DEFERRABLE INITIALLY IMMEDIATE" if not fk.not_deferrable else " NOT DEFERRABLE"
    )
    return (
        f"ALTER TABLE {q(ts.schema_name)}.{q(ts.name)} "
        f"ADD CONSTRAINT {q(fk.name)} FOREIGN KEY ({cols}) "
        f"REFERENCES {q(ts.schema_name)}.{q(fk.ref_table)} ({refs}) "
        f"{fk.match.value} "
        f"ON UPDATE {fk.on_update} ON DELETE {fk.on_delete}{defer};"
    )


def render_constraints(tables: dict[str, TableSchema], selected: list[str]) -> str:
    lines = [HEADER, "BEGIN;\n"]
    any_fk = False
    for tname in selected:
        ts = tables[tname]
        for fk in ts.foreign_keys:
            any_fk = True
            lines.append(_fk_sql(ts, fk))
    if not any_fk:
        lines.append("-- no foreign keys in the selected closure\n")
    lines.append("\nCOMMIT;\n")
    return "\n".join(lines)


def _constraints_inventory(selected: list[str], tables: dict[str, TableSchema]) -> dict:
    return {
        t: {
            "primary_key": (
                [u.name for u in tables[t].unique_constraints if u.is_primary] or None
            ),
            "unique": [u.name for u in tables[t].unique_constraints if not u.is_primary],
            "foreign_keys": [
                {
                    "name": f.name,
                    "columns": f.columns,
                    "references": f"{f.ref_table}({', '.join(f.ref_columns)})",
                    "match": f.match.value,
                    "deferrable": not f.not_deferrable,
                }
                for f in tables[t].foreign_keys
            ],
        }
        for t in selected
    }


def render_manifest(
    selected: list[str],
    tables: dict[str, TableSchema],
    specs: dict,
    data: dict[str, list[Row]],
) -> dict:
    return {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "contains_real_patient_data": False,
        "selected_tables": selected,
        "row_counts": {t: len(data[t]) for t in selected},
        "requested_ranges": {
            t: {c: {"low": r.low, "high": r.high} for c, r in specs[t].ranges.items()}
            for t in selected
        },
        "constraints": _constraints_inventory(selected, tables),
    }


def render_readme(manifest: dict) -> str:
    lines = [
        "# Synthetic referential sample package",
        "",
        "Generated: " + manifest["generated_at_utc"],
        "Contains real patient data: **no** — all values are solver-generated integers.",
        "",
        "## Files",
        "",
        "| file | purpose |",
        "|---|---|",
        "| 01_schema.sql | CREATE TABLE with inline PK/UNIQUE (no FK yet) |",
        "| 02_data.sql | INSERT of exactly the requested row counts |",
        "| 03_constraints.sql | ALTER TABLE ADD CONSTRAINT for every FK (handles cycles) |",
        "| manifest.json | requested ranges, row counts and constraint inventory |",
        "",
        "## Load",
        "",
        "```sh",
        "psql \"$EMPTY_DATABASE_DSN\" -v ON_ERROR_STOP=1 -f 01_schema.sql \\",
        "  -f 02_data.sql -f 03_constraints.sql",
        "```",
        "",
        "## Row counts",
        "",
    ]
    for t, n in manifest["row_counts"].items():
        lines.append(f"* `{t}`: {n} row(s)")
    lines.append("")
    return "\n".join(lines)


def build_package(
    tables: dict[str, TableSchema],
    selected: list[str],
    specs: dict,
    data: dict[str, list[Row]],
) -> dict[str, str]:
    manifest = render_manifest(selected, tables, specs, data)
    return {
        "01_schema.sql": render_schema(tables, selected),
        "02_data.sql": render_data(tables, selected, data),
        "03_constraints.sql": render_constraints(tables, selected),
        "manifest.json": json.dumps(manifest, ensure_ascii=False, indent=2),
        "README.md": render_readme(manifest),
    }


# ---------------------------------------------------------------------------
# Co-load (merge) package: two verified samples combined into one loadable set.
# ---------------------------------------------------------------------------


def render_merge_manifest(
    selected: list[str],
    tables: dict[str, TableSchema],
    data: dict[str, list[Row]],
    job_a: str,
    job_b: str,
    counts_a: dict[str, int],
    counts_b: dict[str, int],
) -> dict:
    return {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "contains_real_patient_data": False,
        "package_kind": "coload_merge",
        "source_jobs": {"first": job_a, "second": job_b},
        "merge_rules": {
            "first_sample": "全部值原样保留",
            "second_sample": (
                "仅主键列与构成有效引用（完整非 NULL 键）的外键列可在整数列类型"
                "边界内改写；NULL 位置不变；每条有效引用仍指向原记录的合并版"
            ),
        },
        "selected_tables": selected,
        "row_counts": {t: len(data[t]) for t in selected},
        "row_counts_by_source": {
            t: {"first": counts_a[t], "second": counts_b[t]} for t in selected
        },
        "constraints": _constraints_inventory(selected, tables),
    }


def render_merge_readme(manifest: dict) -> str:
    lines = [
        "# Merged co-load sample package",
        "",
        "Generated: " + manifest["generated_at_utc"],
        "Contains real patient data: **no** — all values are solver-generated integers.",
        "",
        "## Source jobs",
        "",
        f"* first (kept verbatim): `{manifest['source_jobs']['first']}`",
        f"* second (only PK / validly-referencing FK cells rewritten within "
        f"integer type bounds, NULL positions preserved): "
        f"`{manifest['source_jobs']['second']}`",
        "",
        "## Files",
        "",
        "| file | purpose |",
        "|---|---|",
        "| 01_schema.sql | CREATE TABLE with inline PK/UNIQUE (no FK yet) |",
        "| 02_data.sql | INSERT of both samples (first sample rows, then merged second-sample rows) |",
        "| 03_constraints.sql | ALTER TABLE ADD CONSTRAINT for every FK (handles cycles) |",
        "| manifest.json | source jobs, per-table row counts and constraint inventory |",
        "",
        "## Load",
        "",
        "```sh",
        "psql \"$EMPTY_DATABASE_DSN\" -v ON_ERROR_STOP=1 -f 01_schema.sql \\",
        "  -f 02_data.sql -f 03_constraints.sql",
        "```",
        "",
        "## Row counts (merged totals)",
        "",
    ]
    for t, n in manifest["row_counts"].items():
        src = manifest["row_counts_by_source"][t]
        lines.append(
            f"* `{t}`: {n} row(s) = {src['first']} (first) + {src['second']} (second)"
        )
    lines.append("")
    return "\n".join(lines)


def build_merge_package(
    tables: dict[str, TableSchema],
    selected: list[str],
    data: dict[str, list[Row]],
    job_a: str,
    job_b: str,
    counts_a: dict[str, int],
    counts_b: dict[str, int],
) -> dict[str, str]:
    manifest = render_merge_manifest(
        selected, tables, data, job_a, job_b, counts_a, counts_b
    )
    return {
        "01_schema.sql": render_schema(tables, selected),
        "02_data.sql": render_data(tables, selected, data),
        "03_constraints.sql": render_constraints(tables, selected),
        "manifest.json": json.dumps(manifest, ensure_ascii=False, indent=2),
        "README.md": render_merge_readme(manifest),
    }
